	/**
	 * Zwraca grupę cenową (RC1-RC5) dla kodu RAL lub null, jeśli nie jest przypisany.
	 */
	public static function group(int $code): ?string
	{
		foreach (self::GROUPS as $group => $codes) {
			if (in_array($code, $codes, true)) {
				return $group;
			}
		}

		return null;
	}

	/**
	 * Zwraca kolor sRGB (hex) dla kodu RAL, domyślnie szary jeśli nieznany.
	 */
	public static function hex(int $code): string
	{
		return self::HEX[$code] ?? '#CCCCCC';
	}

	/**
	 * Wszystkie skonfigurowane kody RAL (suma wszystkich grup), posortowane rosnąco.
	 *
	 * @return int[]
	 */
	public static function all(): array
	{
		$codes = array_merge(...array_values(self::GROUPS));
		sort($codes);

		return array_values(array_unique($codes));
	}

	/**
	 * Wyciąga numer RAL (np. 3000) z nazwy/slug terminu atrybutu ("RAL 3000", "ral-3000").
	 */
	public static function codeFromTermName(string $name): ?int
	{
		if (preg_match('/(\d{3,4})/', $name, $matches)) {
			return (int) $matches[1];
		}

		return null;
	}

	/**
	 * Wyciąga wagę w kg (np. 5, 10.5) z nazwy terminu atrybutu wagi ("5kg", "10 kg").
	 */
	public static function weightFromTermName(string $name): ?float
	{
		if (preg_match('/([\d]+(?:[.,]\d+)?)/', $name, $matches)) {
			return (float) str_replace(',', '.', $matches[1]);
		}

		return null;
	}
